GRANT SELECT ON public.fantasposi_players TO authenticated;
GRANT SELECT ON
    public.fantasposi_phases,
    public.fantasposi_missions,
    public.fantasposi_predictions,
    public.fantasposi_player_missions,
    public.fantasposi_player_predictions
TO authenticated;

CREATE POLICY fantasposi_players_read_own
ON public.fantasposi_players FOR SELECT TO authenticated
USING ((SELECT auth.uid()) = user_id);

CREATE POLICY fantasposi_phases_read_for_player
ON public.fantasposi_phases FOR SELECT TO authenticated
USING (EXISTS (
    SELECT 1 FROM public.fantasposi_players player
    WHERE player.wedding_id = fantasposi_phases.wedding_id
      AND player.user_id = (SELECT auth.uid())
      AND player.active
));

CREATE POLICY fantasposi_missions_read_for_player
