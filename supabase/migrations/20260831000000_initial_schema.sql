CREATE OR REPLACE FUNCTION public.reset_backend_sequences()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    table_name text;
    maximum_id bigint;
    sequence_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'weddings', 'media', 'site_assets', 'wedding_schedule', 'wedding_locations',
        'wedding_info_items', 'wedding_story_items', 'wedding_members'
    ] LOOP
        EXECUTE format('SELECT max(id) FROM public.%I', table_name) INTO maximum_id;
        sequence_name := pg_get_serial_sequence('public.' || table_name, 'id');
        IF sequence_name IS NOT NULL THEN
            PERFORM setval(sequence_name, coalesce(maximum_id, 1), maximum_id IS NOT NULL);
        END IF;
    END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION public.reset_backend_sequences() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reset_backend_sequences() TO service_role;
