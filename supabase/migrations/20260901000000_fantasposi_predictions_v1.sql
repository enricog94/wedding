-- FantaSposi Prediction Engine V1.
-- Keeps the original JSON answer columns for backward compatibility while
-- adding relational single-choice options and a frozen scoring ledger.

ALTER TABLE public.fantasposi_predictions
    ADD COLUMN description text,
    ADD COLUMN status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'open', 'closed', 'resolved')),
    ADD COLUMN opens_at timestamptz,
    ADD COLUMN closes_at timestamptz,
    ADD COLUMN correct_option_id bigint,
    ADD CONSTRAINT fantasposi_predictions_open_window_check
        CHECK (opens_at IS NULL OR closes_at IS NULL OR opens_at < closes_at);

UPDATE public.fantasposi_predictions
SET closes_at = locks_at
WHERE closes_at IS NULL AND locks_at IS NOT NULL;

CREATE TABLE public.fantasposi_prediction_options (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wedding_id bigint NOT NULL REFERENCES public.weddings(id) ON DELETE CASCADE,
    prediction_id bigint NOT NULL,
    code text NOT NULL,
    label text NOT NULL,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (prediction_id, wedding_id)
        REFERENCES public.fantasposi_predictions(id, wedding_id) ON DELETE CASCADE,
    UNIQUE (prediction_id, code),
    UNIQUE (id, prediction_id, wedding_id)
);

ALTER TABLE public.fantasposi_predictions
    ADD CONSTRAINT fantasposi_predictions_correct_option_fk
    FOREIGN KEY (correct_option_id, id, wedding_id)
    REFERENCES public.fantasposi_prediction_options(id, prediction_id, wedding_id)
    ON DELETE RESTRICT;

ALTER TABLE public.fantasposi_player_predictions
    ADD COLUMN selected_option_id bigint,
    ADD COLUMN answered_at timestamptz,
    ADD COLUMN resolved_at timestamptz;

UPDATE public.fantasposi_player_predictions
SET answered_at = submitted_at
WHERE answered_at IS NULL;

ALTER TABLE public.fantasposi_player_predictions
    ADD CONSTRAINT fantasposi_player_predictions_selected_option_fk
    FOREIGN KEY (selected_option_id, prediction_id, wedding_id)
    REFERENCES public.fantasposi_prediction_options(id, prediction_id, wedding_id)
    ON DELETE RESTRICT;

CREATE INDEX idx_fantasposi_predictions_wedding_status_phase
    ON public.fantasposi_predictions(wedding_id, status, phase_id, sort_order, id);
CREATE INDEX idx_fantasposi_prediction_options_prediction_order
    ON public.fantasposi_prediction_options(prediction_id, sort_order, id);
CREATE INDEX idx_fantasposi_player_predictions_prediction_status
    ON public.fantasposi_player_predictions(prediction_id, status);

ALTER TABLE public.fantasposi_prediction_options ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.fantasposi_prediction_options FROM anon, authenticated;
GRANT SELECT ON public.fantasposi_prediction_options TO authenticated;

CREATE POLICY fantasposi_prediction_options_read_for_player
ON public.fantasposi_prediction_options FOR SELECT TO authenticated
USING (EXISTS (
    SELECT 1
    FROM public.fantasposi_players player
    WHERE player.wedding_id = fantasposi_prediction_options.wedding_id
      AND player.user_id = (SELECT auth.uid())
      AND player.active
));

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.fantasposi_predictions, public.fantasposi_prediction_options
TO wedding_worker;
GRANT SELECT, INSERT, UPDATE
ON public.fantasposi_player_predictions
TO wedding_worker;
GRANT USAGE, SELECT ON SEQUENCE
    public.fantasposi_predictions_id_seq,
    public.fantasposi_prediction_options_id_seq,
    public.fantasposi_player_predictions_id_seq
TO wedding_worker;

CREATE POLICY fantasposi_predictions_worker_all
ON public.fantasposi_predictions FOR ALL TO wedding_worker
USING (true) WITH CHECK (true);

CREATE POLICY fantasposi_prediction_options_worker_all
ON public.fantasposi_prediction_options FOR ALL TO wedding_worker
USING (true) WITH CHECK (true);

CREATE POLICY fantasposi_player_predictions_worker_select
ON public.fantasposi_player_predictions FOR SELECT TO wedding_worker
USING (true);

CREATE POLICY fantasposi_player_predictions_worker_insert
ON public.fantasposi_player_predictions FOR INSERT TO wedding_worker
WITH CHECK (true);

CREATE POLICY fantasposi_player_predictions_worker_update
ON public.fantasposi_player_predictions FOR UPDATE TO wedding_worker
USING (true) WITH CHECK (true);
